import {test} from "node:test";
import assert from "node:assert/strict";
import {execFileSync} from "node:child_process";
import {mkdtempSync,readFileSync} from "node:fs";
import {tmpdir} from "node:os";
import {join} from "node:path";
process.env.DATABASE_URL="file:"+join(mkdtempSync(join(tmpdir(),"radar-versions-")),"test.db").replaceAll("\\","/");
execFileSync(process.execPath,["node_modules/prisma/build/index.js","migrate","deploy"],{env:process.env,stdio:"ignore",windowsHide:true});
test("migration additive; legacy, approval, restoration and stale/cross-project protection",async()=>{
 const {prisma}=await import("../src/lib/db");
 const V=await import("../src/lib/script-versions");
 const c=await prisma.myChannel.create({data:{name:"Por Que É Assim?"}});
 const idea=await prisma.idea.create({data:{myChannelId:c.id,format:"short",theme:"Thor",titles:"[]",script:"legado",scriptData:'{"falado":[],"cenas":[]}'}});
 const payload={ideaId:idea.id,expectedVersionId:null,content:'{"falado":[],"cenas":[]}',markdown:(code:string,n:number)=>"**Projeto:** "+code+" · versão "+n,category:"história" as const,origin:"test"};
 const a=await V.appendVersion(payload);
 assert.equal(a.number,2);assert.equal(await prisma.scriptVersion.count({where:{ideaId:idea.id}}),2);
 assert.equal((await prisma.idea.findUniqueOrThrow({where:{id:idea.id}})).approvedVersionId,null);
 await V.approveVersion(idea.id,a.id);
 const b=await V.appendVersion({...payload,expectedVersionId:a.id,content:'{"falado":[],"cenas":[],"new":true}'});
 const changed=await prisma.idea.findUniqueOrThrow({where:{id:idea.id}});assert.equal(changed.approvedVersionId,a.id);assert.equal(changed.currentVersionId,b.id);
 await assert.rejects(()=>V.appendVersion({...payload,expectedVersionId:a.id}),/mudou/);
 await assert.rejects(()=>V.approveVersion(idea.id,a.id),/atual/);
 const other=await prisma.idea.create({data:{myChannelId:c.id,format:"short",theme:"Outro",titles:"[]"}});
 await assert.rejects(()=>V.restoreVersion(other.id,a.id,null),/pertence/);
 const restored=await V.restoreVersion(idea.id,a.id,b.id);assert.equal(restored.content,a.content);assert.equal(restored.number,4);
 assert.equal((await prisma.scriptVersion.findUniqueOrThrow({where:{id:b.id}})).content,b.content);
 assert.match(restored.markdown,/versão 4/);
 assert.throws(()=>V.changeCategory("global"),/inválida/);
 const sql=readFileSync("prisma/migrations/20261115180000_script_versions/migration.sql","utf8");assert.doesNotMatch(sql,/DROP\s|DELETE\s+FROM|RENAME\s/i);
 const legacy=await prisma.idea.create({data:{myChannelId:c.id,format:"short",theme:"Antigo",titles:"[]",script:"Texto preservado",scriptData:'{"titulo":"Antigo","duracaoSeg":30,"falado":[{"personagem":"Menino","fala":"Texto preservado"}],"cenas":[],"pendencias":[]}'}});
 const captured=await V.captureLegacyVersion(legacy.id);assert.ok(captured);
 assert.equal(await V.captureLegacyVersion(legacy.id),captured);
 const saved=await prisma.idea.findUniqueOrThrow({where:{id:legacy.id}});
 assert.equal(saved.approvedVersionId,null);assert.equal(saved.scriptData,legacy.scriptData);
 assert.equal(await prisma.scriptVersion.count({where:{ideaId:legacy.id}}),1);
 assert.match(saved.script!,/Referência do canal/);
 await prisma.$disconnect();
});
